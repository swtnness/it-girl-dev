"""
Hacer un programa que lea dos números ingresados por 
el usuario, imprimir la suma de los números
"""

num1 = int(input("Ingrese un número:"))
num2 = int(input("Ingrese otro número:"))
suma = num1 + num2
resta = num1 - num2
multiplicacion = num1 * num2
division = num1 / num2
print(f"La suma de los numeros es: {suma}")
print(f"La resta de los numeros es: {resta}")
print(f"La multiplicacion de los numeros es: {multiplicacion}")
print(f"La divison de los numeros es: {division}")